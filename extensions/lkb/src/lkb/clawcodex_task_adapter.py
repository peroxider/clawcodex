"""Host adapter routing Task-v2 tools to the LKB Plan Graph (spec §6.1).

When ``LKB_PLAN_GRAPH`` is enabled, Task-v2 tool calls are routed to the
LkbApplicationService + PlanCommandDispatcher so the Graph Store is the
single authority.  Only an explicitly disabled flag falls through to the
native Task-v2 path.  Import, board-resolution, and adapter failures are
fail-closed so a configured Graph Store can never be bypassed silently.

TaskOutput is **never** routed here (spec LKB-ADAPT-014): it continues
to use the independent runtime output registry.

This is a thin adapter: it translates Task-v2 tool input into a
:class:`GraphCommand`, executes it via the dispatcher, and rebuilds a
Task-v2-compatible :class:`ToolResult`.  Domain logic lives in
``extensions/lkb/src/lkb/``; nothing here re-implements rules.
"""

from __future__ import annotations

import os
import uuid
from typing import Any

from clawcodex_ext.tool_system.protocol import ToolResult


_SELF_OWNER_SENTINEL = "$self"


def is_plan_graph_active() -> bool:
    """True when LKB Plan Graph should own Task-v2 writes."""
    try:
        from lkb.flags import is_plan_graph_enabled

        return is_plan_graph_enabled()
    except Exception:
        # The host registry is independent of the optional LKB package.
        # If authority was configured, keep routing so the adapter returns
        # a denial instead of silently falling through to native Task-v2.
        from clawcodex_ext.feature_gate import get_registry, register_defaults

        register_defaults()
        return get_registry().is_enabled("LKB_PLAN_GRAPH")


def _repo():
    from lkb.repository import get_repository

    return get_repository()


def _dispatcher():
    from lkb.plan_graph import plan_command_dispatcher

    return plan_command_dispatcher()


def _service():
    from lkb.application import LkbApplicationService

    return LkbApplicationService(repository=_repo())


def _execute(
    kind: str,
    board_id: str,
    plan_id: str,
    payload: dict[str, Any],
    *,
    actor: str,
    command_id: str,
    reason: str | None = None,
    roles: tuple[str, ...] = (),
):
    from lkb.commands import GraphCommand
    from lkb.refs import plan_task_ref

    svc = _service()
    dispatcher = _dispatcher()
    task_id = str(payload.get("task_id", ""))
    routed_payload = {**payload, "plan_id": plan_id}
    command = GraphCommand(
        command_id=command_id,
        board_id=board_id,
        actor=actor,
        kind=kind,
        primary_subject_ref=plan_task_ref(task_id, graph_id=plan_id) if task_id else None,
        payload=routed_payload,
        reason=reason,
        roles=roles,
    )
    return svc.execute(command, validate=dispatcher.validate, apply=dispatcher.apply)


def _actor(context: Any) -> str:
    """Best-effort trusted actor identity from the context."""
    for attr in ("agent_id", "actor", "session_id"):
        val = getattr(context, attr, None)
        if isinstance(val, str) and val:
            return val
    return "agent"


def resolve_task_owner(tool_input: dict[str, Any], context: Any) -> dict[str, Any]:
    """Resolve the model-safe self-owner sentinel at the trusted host boundary.

    Models do not know the opaque ``ToolContext.agent_id`` generated by the
    host.  Requiring them to copy that value made ordinary claims look like
    third-party transfers and fail with ``override_not_authorized``.  ``$self``
    is therefore a reserved transport value: the host replaces it with the
    trusted actor before command classification, hashing, validation, or the
    native Task-v2 fallback sees the update.
    """

    owner = tool_input.get("owner")
    if not isinstance(owner, str) or owner.strip().casefold() != _SELF_OWNER_SENTINEL:
        return tool_input
    return {**tool_input, "owner": _actor(context)}


def _actor_roles(context: Any) -> tuple[str, ...]:
    """Return host-asserted roles without consulting model-controlled input."""
    raw = getattr(context, "actor_roles", ())
    if isinstance(raw, str) or not isinstance(raw, (list, tuple)):
        return ()
    return tuple(
        dict.fromkeys(role.strip() for role in raw if isinstance(role, str) and role.strip())
    )


def _board_id(context: Any) -> str:
    """Resolve the board id for this context's workspace."""
    repo = _repo()
    return repo.resolve_board(
        getattr(context, "workspace_root", None),
        session_id=getattr(context, "session_id", None),
    ).board_id


def _plan_id(context: Any, board_id: str) -> str:
    """Resolve and persist this session's Plan binding inside the Board."""
    from lkb.plan_scope import current_session_id, resolve_plan

    requested = getattr(context, "lkb_plan_id", None)
    if not isinstance(requested, str) or not requested:
        requested = os.getenv("CLAWCODEX_LKB_PLAN_ID") or None
    header = resolve_plan(
        _repo(),
        board_id,
        current_session_id(context),
        requested_plan_id=requested,
    )
    try:
        context.lkb_plan_id = header.plan_id
    except Exception:
        pass
    return header.plan_id


def _idempotency_key(context: Any, tool_input: dict[str, Any]) -> str | None:
    """Return a stable idempotency key for this call, or None.

    Priority: explicit ``idempotency_key`` / ``request_id`` in the tool
    input, then the ToolContext ``tool_use_id``.
    """
    for key in ("idempotency_key", "request_id"):
        val = tool_input.get(key)
        if isinstance(val, str) and val.strip():
            return val.strip()
    tool_use_id = getattr(context, "tool_use_id", None)
    if isinstance(tool_use_id, str) and tool_use_id:
        return tool_use_id
    return None


def _command_id(
    context: Any,
    tool_name: str,
    tool_input: dict[str, Any],
    *,
    plan_id: str,
) -> str:
    """Stable command id for idempotent retry (issue #12).

    Transport-layer retries must not create duplicate Tasks.  The command
    id is reused from the idempotency key (see :func:`_idempotency_key`),
    falling back to a fresh UUID when no stable key is available.

    The LKB Store deduplicates on ``(command_id, request_hash)``: a retry
    with the same id and payload returns the first result instead of
    re-applying (spec §5.10, LKB-STORE-004).
    """
    key = _idempotency_key(context, tool_input)
    if key:
        return f"host-{plan_id}-{tool_name.lower()}-{key}"
    return f"host-{plan_id}-{tool_name.lower()}-{uuid.uuid4().hex[:8]}"


def _task_lkb_summary(
    snap: Any,
    plan: Any,
    ref: Any,
    node: Any,
    blocked_by: list[str],
    validation_run: dict[str, Any] | None,
) -> dict[str, Any]:
    """Build the nested ``lkb`` summary for one task (spec §8.2)."""
    payload = node.payload if hasattr(node, "payload") else {}
    if not isinstance(payload, dict):
        payload = {}
    derived_raw = str(payload.get("derived_status", "") or "")
    state = str(node.state or "pending")
    # Derived status: needs_recheck/needs_review win over base state.
    if derived_raw in ("needs_recheck", "needs_review"):
        derived = derived_raw
    elif state == "completed":
        derived = "verified"
    elif ref in plan.blocked_ids:
        derived = "blocked"
    elif state == "in_progress":
        derived = "running"
    else:
        derived = "ready"
    active_blockers = [b for b in blocked_by if _blocker_active(snap, ref.graph, b)]
    claimable = derived == "ready" and not (node.owner or None)
    if validation_run is not None:
        validation = {
            "status": "validated",
            "result": validation_run.get("result", ""),
            "runId": validation_run.get(
                "validationRunId", validation_run.get("validation_run_id", "")
            ),
        }
    else:
        validation = {"status": "unvalidated"}
    consistency_state = "stale" if derived == "needs_recheck" else "clean"
    next_actions: list[str] = []
    next_action_commands: list[dict[str, Any]] = []
    if derived == "ready":
        if not (node.owner or None):
            next_actions.append("claim_task")
            next_action_commands.append(
                _tool_action(
                    "claim_task",
                    "TaskUpdate",
                    {"taskId": ref.id, "owner": _SELF_OWNER_SENTINEL},
                    "Claim this task as the current Agent.",
                )
            )
        else:
            next_actions.append("start_task")
            next_action_commands.append(
                _tool_action(
                    "start_task",
                    "TaskUpdate",
                    {"taskId": ref.id, "status": "in_progress"},
                    "Start the task after it has been claimed.",
                )
            )
    elif derived == "running":
        next_actions.append("complete_task")
        next_action_commands.append(
            _tool_action(
                "complete_task",
                "TaskUpdate",
                {"taskId": ref.id, "status": "completed"},
                "Complete the running task.",
            )
        )
    elif derived == "needs_recheck":
        next_actions.append("revalidate_task")
        next_action_commands.append(
            _tool_action(
                "revalidate_task",
                "Lkb",
                {"action": "revalidate", "taskId": ref.id},
                "Revalidate this task after its upstream work is current.",
            )
        )
    elif derived == "blocked":
        next_actions.append("complete_prerequisite")
        next_action_commands.append(
            _tool_action(
                "explain_blockers",
                "Lkb",
                {"action": "explain", "taskId": ref.id},
                "Inspect the active prerequisite chain before retrying.",
            )
        )
    return {
        "derivedStatus": derived,
        "claimable": claimable,
        "activeBlockers": active_blockers,
        "validation": validation,
        "consistency": {
            "state": consistency_state,
            "issueCount": 1 if derived == "needs_recheck" else 0,
        },
        "nextActions": next_actions,
        "nextActionCommands": next_action_commands,
    }


def _blocker_active(snap: Any, graph_id: str, task_id: str) -> bool:
    """True if *task_id* is an unsatisfied prerequisite (not verified)."""
    from lkb.graph_types import NodeRef

    ref = NodeRef(graph_id, "task", task_id)
    node = snap.nodes.get(ref)
    if node is None:
        return False
    if node.state != "completed":
        return True
    payload = node.payload if isinstance(node.payload, dict) else {}
    return str(payload.get("derived_status", "") or "") in ("needs_recheck", "needs_review")


def _build_projection(snap: Any, plan_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
    """Project a snapshot into Task-v2 tasks + a top-level ``lkbBoard``.

    Spec §8.2 / issue #5: each task carries ``blocks`` / ``blockedBy``
    computed from the canonical ``depends_on`` edges (not hardcoded
    empty), plus a nested ``lkb`` summary; the TaskList top level carries
    an ``lkbBoard`` aggregate.
    """
    from lkb.graph_types import PlanSnapshot

    plan = PlanSnapshot.from_graph(snap)
    # adjacency from depends_on edges (source depends on target).
    blocked_by_map: dict[str, list[str]] = {}
    blocks_map: dict[str, list[str]] = {}
    for edge in snap.edges.values():
        if edge.graph != plan_id or edge.type != "depends_on":
            continue
        dependent = edge.source.id
        prerequisite = edge.target.id
        blocked_by_map.setdefault(dependent, []).append(prerequisite)
        blocks_map.setdefault(prerequisite, []).append(dependent)
    # validation runs indexed by subject_ref.
    validation_by_ref: dict[str, dict[str, Any]] = {}
    for vr in snap.validation_runs.values() if hasattr(snap, "validation_runs") else []:
        if not isinstance(vr, dict):
            continue
        subject = vr.get("subjectRef") or vr.get("subject_ref")
        if isinstance(subject, dict):
            subject = f"{subject.get('graph')}:{subject.get('kind')}:{subject.get('id')}"
        if isinstance(subject, str) and subject:
            validation_by_ref[subject] = vr

    tasks: dict[str, Any] = {}
    counts = {"ready": 0, "running": 0, "blocked": 0, "needsRecheck": 0}
    for ref, node in snap.nodes.items():
        if ref.graph != plan_id or ref.kind != "task":
            continue
        payload = node.payload if hasattr(node, "payload") else {}
        if not isinstance(payload, dict):
            payload = {}
        bby = sorted(blocked_by_map.get(ref.id, []))
        blk = sorted(blocks_map.get(ref.id, []))
        lkb = _task_lkb_summary(snap, plan, ref, node, bby, validation_by_ref.get(ref.to_str()))
        tasks[ref.id] = {
            "id": ref.id,
            "subject": node.title,
            "description": str(payload.get("description", "")),
            "activeForm": str(payload.get("activeForm", node.title)),
            "status": str(node.state or "pending"),
            "owner": node.owner,
            "blocks": blk,
            "blockedBy": bby,
            "metadata": dict(payload.get("metadata", {}) or {}),
            "output": str(payload.get("output", "")),
            "lkb": lkb,
        }
        d = lkb["derivedStatus"]
        if d == "ready":
            counts["ready"] += 1
        elif d == "running":
            counts["running"] += 1
        elif d == "blocked":
            counts["blocked"] += 1
        elif d == "needs_recheck":
            counts["needsRecheck"] += 1
    graph = snap.graphs.get(plan_id)
    metadata = graph.metadata if graph is not None else {}
    lkb_board = {
        "boardId": snap.board_id,
        "revision": snap.store_revision,
        "planId": plan_id,
        "planTitle": str(metadata.get("title") or plan_id),
        "planState": str(metadata.get("state") or "active"),
        "planRevision": graph.revision if graph is not None else 0,
        "counts": counts,
    }
    return tasks, lkb_board


def _hydrate(context: Any, board_id: str, plan_id: str) -> dict[str, Any]:
    """Refresh ``context.tasks`` from the Store; report divergence.

    Spec §15.2/§15.3 / issue #7: when the context already holds in-memory
    tasks that are NOT in the Store (first enable, or divergence after a
    disable window), those tasks are NOT silently dropped - they are
    preserved and reported as ``divergence.unimported`` so the caller can
    choose to ``import_current_tasks`` rather than losing data.
    """
    try:
        repo = _repo()
        snap = repo.load_snapshot(board_id)
    except Exception:
        # Hydration is best-effort; the Store remains authoritative.
        return {"divergence": None}
    tasks, lkb_board = _build_projection(snap, plan_id)
    divergence: dict[str, Any] | None = None
    if hasattr(context, "tasks") and context.tasks:
        store_ids = set(tasks)
        context_ids = {
            tid for tid, t in context.tasks.items() if isinstance(t, dict) and t.get("id")
        }
        unimported = sorted(context_ids - store_ids)
        if unimported:
            # Preserve the in-memory tasks the Store does not know about;
            # do NOT clear them.  Merge Store tasks alongside.
            divergence = {
                "unimported": unimported,
                "boardTaskCount": len(store_ids),
                "hint": "import_current_tasks required to merge these into the Board",
            }
            merged = dict(context.tasks)
            # Overlay Store tasks (authoritative for shared ids).
            merged.update(tasks)
            context.tasks.clear()
            context.tasks.update(merged)
            return {"divergence": divergence, "lkbBoard": lkb_board}
    if hasattr(context, "tasks"):
        context.tasks.clear()
        context.tasks.update(tasks)
    return {"divergence": None, "lkbBoard": lkb_board}


def try_handle(
    tool_name: str, tool_input: dict[str, Any], context: Any
) -> tuple[bool, ToolResult | None]:
    """Route a Task-v2 tool call to the LKB Plan Graph.

    Returns ``(True, ToolResult)`` when handled, ``(False, None)`` to fall
    through to the native path.  TaskOutput is never routed here.
    """
    if not is_plan_graph_active():
        return False, None
    if tool_name == "TaskOutput":
        return False, None  # LKB-ADAPT-014
    if tool_name == "TaskUpdate":
        tool_input = resolve_task_owner(tool_input, context)

    try:
        board_id = _board_id(context)
        plan_id = _plan_id(context, board_id)
        actor = _actor(context)
        roles = _actor_roles(context)
    except Exception as exc:  # noqa: BLE001 - configured authority is fail-closed
        message = f"LKB board resolution error: {exc}"
        payload = _adapter_error_payload(tool_name, message)
        if tool_name == "TaskCreate":
            payload["task"] = {
                "id": "",
                "subject": str(tool_input.get("subject", "")),
            }
        elif tool_name == "TaskGet":
            payload["task"] = None
        elif tool_name == "TaskUpdate":
            payload["taskId"] = _task_id_of(tool_input)
        return True, ToolResult(name=tool_name, is_error=True, output=payload)

    cid = _command_id(context, tool_name, tool_input, plan_id=plan_id)

    try:
        if tool_name == "TaskCreate":
            return True, _handle_create(tool_input, context, board_id, plan_id, actor, cid)
        if tool_name == "TaskGet":
            return True, _handle_get(tool_input, context, board_id, plan_id)
        if tool_name == "TaskList":
            return True, _handle_list(tool_input, context, board_id, plan_id)
        if tool_name == "TaskUpdate":
            return True, _handle_update(tool_input, context, board_id, plan_id, actor, cid, roles)
    except Exception as exc:  # noqa: BLE001 - adapter must not crash the tool
        # LKB-ADAPT-009: return a denial-shaped payload so legacy clients
        # that ignore ``lkb`` still see a consumable native shape.
        message = f"LKB adapter error: {exc}"
        if tool_name == "TaskCreate":
            payload = {
                "task": {"id": "", "subject": str(tool_input.get("subject", ""))},
                "success": False,
                "status": "denied",
                "reason": {"code": "adapter_error", "message": message},
                "lkb": {"decision": "denied", "adapterError": message, "toolName": tool_name},
            }
        elif tool_name == "TaskGet":
            payload = {
                "task": None,
                "success": False,
                "status": "denied",
                "reason": {"code": "adapter_error", "message": message},
                "lkb": {"decision": "denied", "adapterError": message, "toolName": tool_name},
            }
        elif tool_name == "TaskUpdate":
            payload = _adapter_error_payload(tool_name, message)
            payload["taskId"] = _task_id_of(tool_input)
        else:
            payload = {
                "success": False,
                "status": "denied",
                "reason": {"code": "adapter_error", "message": message},
                "lkb": {"decision": "denied", "adapterError": message, "toolName": tool_name},
            }
        return True, ToolResult(name=tool_name, is_error=True, output=payload)

    return False, None


def _task_id_of(tool_input: dict[str, Any]) -> str:
    """Read the task id from either snake_case or camelCase input."""
    return str(tool_input.get("task_id") or tool_input.get("taskId") or "")


def _metadata_type_error(tool_input: dict[str, Any]) -> str | None:
    """Reject malformed ``metadata`` before it reaches the Graph Store.

    A non-dict ``metadata`` or ``metadata.lkb`` would be stored verbatim and
    later break the Task-v2 projection, so deny it before persistence.
    """
    metadata = tool_input.get("metadata")
    if metadata is None:
        return None
    if not isinstance(metadata, dict):
        return "metadata must be an object when provided"
    if "owner" in metadata:
        return (
            "metadata.owner is reserved and never changes task ownership; "
            "use top-level owner='$self' to claim the task"
        )
    lkb_meta = metadata.get("lkb")
    if lkb_meta is not None and not isinstance(lkb_meta, dict):
        return "metadata.lkb must be an object when provided"
    return None


def _tool_action(
    action: str,
    tool: str,
    tool_input: dict[str, Any],
    description: str,
) -> dict[str, Any]:
    """Build a model-executable recovery/next-action descriptor."""

    return {
        "action": action,
        "tool": tool,
        "input": tool_input,
        "description": description,
    }


def _reason_code(reason: Any) -> str:
    text = str(reason or "")
    known_codes = (
        "override_not_authorized",
        "owner_required",
        "already_claimed",
        "already_resolved",
        "blocked",
        "dependency_cycle",
        "task_not_found",
        "invalid_transition",
        "invalid_state_transition",
        "revision_conflict",
    )
    for code in known_codes:
        if code in text:
            return code
    prefix = text.partition(":")[0].strip()
    return prefix if prefix and " " not in prefix else "update_denied"


def _recovery_actions(task_id: str, context: Any, reason: Any) -> list[dict[str, Any]]:
    """Return safe, directly callable recovery actions for a denial."""

    task = context.tasks.get(task_id) if hasattr(context, "tasks") else None
    task = task if isinstance(task, dict) else {}
    status = str(task.get("status") or "")
    owner = task.get("owner")
    code = _reason_code(reason)

    if code == "already_resolved" and status == "completed":
        return [
            _tool_action(
                "reopen_task",
                "TaskUpdate",
                {
                    "taskId": task_id,
                    "status": "pending",
                    "reason": "Reopen completed task for additional work.",
                },
                "Explicitly reopen the completed task; LKB will release its old claim "
                "and propagate downstream rechecks.",
            )
        ]
    if code in ("override_not_authorized", "owner_required") and not owner:
        return [
            _tool_action(
                "claim_task",
                "TaskUpdate",
                {"taskId": task_id, "owner": _SELF_OWNER_SENTINEL},
                "Claim with the host-resolved self sentinel; do not invent an Agent id.",
            )
        ]
    if (
        code in ("invalid_transition", "invalid_state_transition", "update_denied")
        and status == "pending"
    ):
        if not owner:
            return [
                _tool_action(
                    "claim_task",
                    "TaskUpdate",
                    {"taskId": task_id, "owner": _SELF_OWNER_SENTINEL},
                    "Claim the pending task before starting it.",
                )
            ]
        return [
            _tool_action(
                "start_task",
                "TaskUpdate",
                {"taskId": task_id, "status": "in_progress"},
                "Move through the required pending to in_progress transition.",
            )
        ]
    if code == "blocked":
        return [
            _tool_action(
                "explain_blockers",
                "Lkb",
                {"action": "explain", "taskId": task_id},
                "Inspect and complete the active prerequisites before retrying.",
            )
        ]
    return [
        _tool_action(
            "inspect_task",
            "TaskGet",
            {"taskId": task_id},
            "Refresh the authoritative task projection before choosing the next transition.",
        )
    ]


def _lkb_denied_payload(
    result: Any,
    task_id: str = "",
    context: Any | None = None,
) -> dict[str, Any]:
    """Build the ``lkb`` sub-payload for a denied command (spec §6.1, LKB-ADAPT-009).

    LKB-specific audit fields live under ``lkb``; the outer payload preserves
    the native Task-v2 fields so legacy clients that ignore ``lkb`` still see a
    consumable shape.
    """
    payload: dict[str, Any] = {
        "decision": "denied",
        "commandId": getattr(result, "command_id", None),
    }
    validation_run_id = getattr(result, "validation_run_id", None)
    if validation_run_id:
        payload["validationRunId"] = validation_run_id
    if result.reason:
        payload["reason"] = result.reason
    payload["nextActions"] = (
        _recovery_actions(task_id, context, result.reason)
        if task_id and context is not None
        else []
    )
    return payload


def _adapter_error_payload(tool_name: str, message: str) -> dict[str, Any]:
    """Build a denial-shaped payload for an adapter-level exception.

    Follows LKB-ADAPT-009: native fields stay consumable; the LKB-specific
    error detail is isolated under ``lkb``.
    """
    return {
        "success": False,
        "status": "denied",
        "reason": {"code": "adapter_error", "message": message},
        "lkb": {"decision": "denied", "adapterError": message, "toolName": tool_name},
        "taskId": "",
        "updatedFields": [],
    }


def _handle_create(tool_input, context, board_id, plan_id, actor, cid) -> ToolResult:
    subject = str(tool_input.get("subject", ""))
    description = str(tool_input.get("description", ""))
    active_form = str(tool_input.get("activeForm", "") or subject)
    metadata_error = _metadata_type_error(tool_input)
    if metadata_error is not None:
        # LKB-ADAPT-009: denial keeps the native TaskCreate shape consumable.
        return ToolResult(
            name="TaskCreate",
            is_error=True,
            output={
                "task": {"id": "", "subject": subject},
                "success": False,
                "status": "denied",
                "reason": {"code": "invalid_metadata", "message": metadata_error},
                "lkb": {
                    "decision": "denied",
                    "adapterError": metadata_error,
                    "toolName": "TaskCreate",
                },
            },
        )
    metadata = dict(tool_input.get("metadata", {}) or {})
    key = _idempotency_key(context, tool_input)
    if key:
        # Deterministic task_id so a transport retry with the same key
        # reproduces the exact payload -> same request_hash -> the Store
        # returns the first result instead of creating a duplicate Task
        # (issue #12, spec §5.10).
        task_id = f"T-{uuid.uuid5(uuid.NAMESPACE_DNS, f'taskcreate/{key}').hex[:8]}"
    else:
        task_id = f"T-{uuid.uuid4().hex[:8]}"
    result = _execute(
        "create_task",
        board_id,
        plan_id,
        {
            "task_id": task_id,
            "subject": subject,
            "description": description,
            "activeForm": active_form,
            "metadata": metadata,
        },
        actor=actor,
        command_id=cid,
    )
    _hydrate(context, board_id, plan_id)
    if result.decision == "committed":
        return ToolResult(name="TaskCreate", output={"task": {"id": task_id, "subject": subject}})
    # LKB-ADAPT-009: keep native TaskCreate fields consumable; LKB detail under ``lkb``.
    return ToolResult(
        name="TaskCreate",
        is_error=True,
        output={
            "task": {"id": task_id, "subject": subject},
            "success": False,
            "status": "denied",
            "reason": {"code": "create_denied", "message": result.reason or "create denied"},
            "lkb": _lkb_denied_payload(result),
        },
    )


def _handle_get(tool_input, context, board_id, plan_id) -> ToolResult:
    task_id = _task_id_of(tool_input)
    _hydrate(context, board_id, plan_id)
    task = context.tasks.get(task_id) if hasattr(context, "tasks") else None
    if task is None:
        # LKB-ADAPT-009: native TaskGet returns ``{"task": None}`` when the
        # task is missing — preserve that shape so legacy clients keep working.
        return ToolResult(name="TaskGet", output={"task": None})
    return ToolResult(name="TaskGet", output={"task": task})


def _handle_list(tool_input, context, board_id, plan_id) -> ToolResult:
    hydration = _hydrate(context, board_id, plan_id)
    tasks = list(context.tasks.values()) if hasattr(context, "tasks") else []
    output: dict[str, Any] = {"tasks": tasks}
    # Spec §8.2 / issue #5: top-level lkbBoard aggregate.
    lkb_board = hydration.get("lkbBoard")
    if lkb_board:
        output["lkbBoard"] = lkb_board
    divergence = hydration.get("divergence")
    if divergence:
        output["divergence"] = divergence
    return ToolResult(name="TaskList", output=output)


def _handle_update(tool_input, context, board_id, plan_id, actor, cid, roles=()) -> ToolResult:
    task_id = _task_id_of(tool_input)
    metadata_error = _metadata_type_error(tool_input)
    if metadata_error is not None:
        # LKB-ADAPT-009: denial keeps the native TaskUpdate shape consumable.
        return ToolResult(
            name="TaskUpdate",
            is_error=True,
            output={
                "success": False,
                "taskId": task_id,
                "updatedFields": [],
                "status": "denied",
                "reason": {"code": "invalid_metadata", "message": metadata_error},
                "nextActions": [
                    _tool_action(
                        "claim_task",
                        "TaskUpdate",
                        {"taskId": task_id, "owner": _SELF_OWNER_SENTINEL},
                        "Use the ownership field, not metadata.owner, to claim the task.",
                    )
                ],
                "lkb": {
                    "decision": "denied",
                    "adapterError": metadata_error,
                    "toolName": "TaskUpdate",
                    "nextActions": [
                        _tool_action(
                            "claim_task",
                            "TaskUpdate",
                            {"taskId": task_id, "owner": _SELF_OWNER_SENTINEL},
                            "Use the ownership field, not metadata.owner, to claim the task.",
                        )
                    ],
                },
            },
        )
    payload: dict[str, Any] = {"task_id": task_id}

    status = tool_input.get("status")
    owner = tool_input.get("owner")
    add_blocked_by = tool_input.get("addBlockedBy")
    add_blocks = tool_input.get("addBlocks")
    remove_blocked_by = tool_input.get("removeBlockedBy")
    remove_blocks = tool_input.get("removeBlocks")
    metadata = tool_input.get("metadata")
    for field in ("subject", "description", "activeForm"):
        if field in tool_input:
            payload[field] = tool_input[field]
    if status is not None:
        payload["status"] = str(status)
    if owner is not None:
        payload["owner"] = owner
    if add_blocked_by:
        payload["addBlockedBy"] = (
            list(add_blocked_by) if isinstance(add_blocked_by, list) else [add_blocked_by]
        )
    if add_blocks:
        payload["addBlocks"] = list(add_blocks) if isinstance(add_blocks, list) else [add_blocks]
    if remove_blocked_by:
        payload["removeBlockedBy"] = (
            list(remove_blocked_by) if isinstance(remove_blocked_by, list) else [remove_blocked_by]
        )
    if remove_blocks:
        payload["removeBlocks"] = (
            list(remove_blocks) if isinstance(remove_blocks, list) else [remove_blocks]
        )
    if metadata is not None:
        payload["metadata"] = dict(metadata or {})

    # Spec §6.1 / §6.4: classify the TaskUpdate into a single domain command.
    #   - owner set to a *different* actor → transfer_task (never trust the
    #     model to silently reassign ownership; requires force_override_roles
    #     + reason, audited under the Board lock).
    #   - owner set to the same actor (or empty) with no other sub-intent →
    #     claim_task.
    #   - more than one sub-intent present → patch_task (atomic composite).
    #   - exactly one sub-intent → the matching single-intent command.
    sub_intent_count = sum(
        bool(x)
        for x in (
            status is not None,
            owner is not None,
            add_blocked_by,
            add_blocks,
            remove_blocked_by,
            remove_blocks,
            metadata is not None,
            any(f in tool_input for f in ("subject", "description", "activeForm")),
        )
    )
    dependency_item_count = sum(
        len(payload.get(key, ()))
        for key in ("addBlockedBy", "addBlocks", "removeBlockedBy", "removeBlocks")
    )
    owner_is_transfer = owner is not None and str(owner) != actor and str(owner).strip() != ""

    if sub_intent_count > 1 or dependency_item_count > 1:
        kind = "patch_task"
    elif owner_is_transfer:
        kind = "transfer_task"
        payload = {"task_id": task_id, "new_owner": str(owner)}
    elif status is not None:
        kind = {
            "pending": "reopen_task",
            "in_progress": "start_task",
            "completed": "complete_task",
            "deleted": "delete_task",
        }.get(str(status), "patch_task")
    elif owner is not None:
        # owner == actor: self-claim.
        kind = "claim_task" if str(owner).strip() else "release_task"
        payload = {"task_id": task_id}
    elif add_blocked_by:
        prereq = str(add_blocked_by[0] if isinstance(add_blocked_by, list) else add_blocked_by)
        kind = "add_dependency"
        payload = {"task_id": task_id, "depends_on": prereq}
    elif add_blocks:
        blocked = str(add_blocks[0] if isinstance(add_blocks, list) else add_blocks)
        kind = "add_dependency"
        payload = {"task_id": blocked, "depends_on": task_id}
    elif remove_blocked_by:
        prereq = str(
            remove_blocked_by[0] if isinstance(remove_blocked_by, list) else remove_blocked_by
        )
        kind = "remove_dependency"
        payload = {"task_id": task_id, "depends_on": prereq}
    elif remove_blocks:
        blocked = str(remove_blocks[0] if isinstance(remove_blocks, list) else remove_blocks)
        kind = "remove_dependency"
        payload = {"task_id": blocked, "depends_on": task_id}
    elif metadata is not None:
        kind = "update_task_fields"
        payload = {"task_id": task_id, "metadata": dict(metadata or {})}
    elif any(f in tool_input for f in ("subject", "description", "activeForm")):
        kind = "update_task_fields"
        payload = {"task_id": task_id}
        for field in ("subject", "description", "activeForm"):
            if field in tool_input:
                payload[field] = tool_input[field]
    else:
        kind = "update_task_fields"

    reason = tool_input.get("reason") or tool_input.get("overrideReason")
    previous_task = context.tasks.get(task_id) if hasattr(context, "tasks") else None
    previous_status = previous_task.get("status") if isinstance(previous_task, dict) else None
    execute_kwargs: dict[str, Any] = {
        "actor": actor,
        "command_id": cid,
        "reason": reason,
    }
    if roles:
        execute_kwargs["roles"] = tuple(roles)
    result = _execute(kind, board_id, plan_id, payload, **execute_kwargs)
    _hydrate(context, board_id, plan_id)
    if result.decision == "committed":
        updated_fields: list[str] = []
        for field in ("subject", "description", "activeForm", "owner"):
            if field in tool_input:
                updated_fields.append(field)
        if status is not None:
            updated_fields.append("deleted" if str(status) == "deleted" else "status")
        if add_blocked_by or remove_blocked_by:
            updated_fields.append("blockedBy")
        if add_blocks or remove_blocks:
            updated_fields.append("blocks")
        if metadata is not None:
            updated_fields.append("metadata")
        updated_fields = list(dict.fromkeys(updated_fields))
        current_task = context.tasks.get(task_id) if hasattr(context, "tasks") else None
        task_projection = (
            {**dict(current_task), "updated": True}
            if isinstance(current_task, dict)
            else {"id": task_id, "updated": True}
        )
        output: dict[str, Any] = {
            "success": True,
            "taskId": task_id,
            "updatedFields": updated_fields,
            "task": task_projection,
        }
        if result.claim_id:
            output["claimId"] = result.claim_id
        if result.affected_refs:
            output["affectedRefs"] = list(result.affected_refs)
        if status is not None and str(status) != "deleted" and previous_status != str(status):
            output["statusChange"] = {"from": str(previous_status), "to": str(status)}
        return ToolResult(name="TaskUpdate", output=output)
    # LKB-ADAPT-009: native TaskUpdate denial carries success/taskId/updatedFields
    # at the top level so legacy clients that ignore ``lkb`` still consume the
    # result; LKB-specific audit detail lives under ``lkb``.
    denial_lkb = _lkb_denied_payload(result, task_id, context)
    return ToolResult(
        name="TaskUpdate",
        is_error=True,
        output={
            "success": False,
            "taskId": task_id,
            "updatedFields": [],
            "status": "denied",
            "reason": {
                "code": _reason_code(result.reason),
                "message": result.reason or "update denied",
            },
            "nextActions": denial_lkb["nextActions"],
            "lkb": denial_lkb,
        },
    )
