#!/usr/bin/env python3
"""Regenerate downstream overlay patches for an extracted upstream commit.

This script is now a thin CLI wrapper around
``upstream_sync.core.patch_generator.PatchGenerator.regenerate()``.

The generated queue models this invariant::

    src/upstream/{commit} + patches/upstream/{commit}/series == src/

Line endings are normalized only for comparison. Patch payloads preserve the
current src/ bytes so applying the queue recreates the downstream tree exactly.

Strategy: "strict reconstruction"
================================

The patch queue must be sufficient to reconstruct ``src/`` from the upstream
base. To that end the script emits four classes of patches:

* **modified** — fork-side delta on top of the upstream base. Generated by
  ``diff -u upstream/.../file src/.../file``.
* **new** — files that exist only under ``src/`` (fork-only additions). These
  are emitted as ``new file mode`` patches so the queue remains self-contained.
* **deleted** — files present in the upstream base but absent from ``src/``
  because the fork removed them. Opt-in via ``--allow-deletes``.
* **(implicit preserve)** — any upstream file that is also in ``--preserve``
  is kept from the base. No patch is generated; if ``src/`` had a different
  version it is dropped.

Usage
-----
::

    python scripts/regenerate_patches.py --commit b24b8cb
    python scripts/regenerate_patches.py --commit b24b8cb --allow-deletes
    python scripts/regenerate_patches.py --commit b24b8cb \\
        --preserve src/cli/help.py --preserve src/config/defaults.yaml
    python scripts/regenerate_patches.py --commit b24b8cb \\
        --preserve-file patches/upstream/b24b8cb/preserve.list
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Allow running directly from the repo root
PROJECT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT))

from upstream_sync.core.patch_generator import PatchGenerator


DEFAULT_SRC = PROJECT / "src"
DEFAULT_UPSTREAM_ROOT = PROJECT / "src" / "upstream"
DEFAULT_PATCH_ROOT = PROJECT / "patches" / "upstream"


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--commit", required=True, help="Upstream snapshot under src/upstream/{commit}"
    )
    parser.add_argument("--src", type=Path, default=DEFAULT_SRC, help="Downstream source tree")
    parser.add_argument("--upstream-root", type=Path, default=DEFAULT_UPSTREAM_ROOT)
    parser.add_argument("--patch-root", type=Path, default=DEFAULT_PATCH_ROOT)
    parser.add_argument(
        "--allow-deletes",
        action="store_true",
        help="Generate delete patches for files present upstream but absent downstream",
    )
    parser.add_argument(
        "--preserve",
        action="append",
        default=[],
        metavar="REL_PATH",
        help="Relative path (under src/) to preserve from the upstream base. "
        "May be passed multiple times. These files produce no patch.",
    )
    parser.add_argument(
        "--preserve-file",
        type=Path,
        default=None,
        help="File containing one relative path per line of files to preserve.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    preserve = PatchGenerator.collect_preserve(
        preserve_args=args.preserve,
        preserve_file_path=args.preserve_file,
    )

    # Use a minimal config — the regenerate path doesn't read upstream-sync.yaml;
    # all paths are passed explicitly.
    generator = PatchGenerator(PROJECT, None)  # type: ignore[arg-type]

    try:
        result = generator.regenerate(
            commit=args.commit,
            src_dir=args.src,
            upstream_dir=args.upstream_root / args.commit,
            patch_root=args.patch_root / args.commit,
            allow_deletes=args.allow_deletes,
            preserve=preserve,
        )
    except FileNotFoundError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except RuntimeError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2

    print(f"Modified files: {result.modified_count}")
    print(f"New files (fork-only): {result.new_count}")
    print(f"Deleted files (by fork): {result.deleted_count}")
    print(f"Preserved files (new in upstream base, kept): {result.preserved_count}")
    print(f"Total patches: {len(result.patch_entries)}")
    print(f"Total size: {result.total_size:,} bytes ({result.total_size / 1024 / 1024:.1f} MB)")
    print(f"Patch directory: {result.patch_dir}")
    print(f"Series file: {result.series_file}")
    print(f"Compatibility series file: {result.compatibility_series_file}")
    if result.preserved_files:
        print()
        print("Preserved files (no patch, kept from upstream base):")
        for rel in sorted(result.preserved_files):
            print(f"  {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
